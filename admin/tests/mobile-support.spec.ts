import { test, expect } from '@playwright/test';

test('管理员维护职务工作电话并查看和退出员工设备', async ({ page, request }) => {
  const login = await request.post('/api/auth/login', { data: { login: 'admin', password: process.env.OA_ADMIN_PASSWORD || 'Admin@2026Verified' } });
  expect(login.ok()).toBeTruthy();
  const headers = { Authorization: 'Bearer ' + (await login.json()).token };
  const departments = await (await request.get('/api/admin/departments', { headers })).json();
  const employeeNo = 'device' + Date.now();
  const created = await request.post('/api/admin/users', { headers, data: { employeeNo, name: employeeNo, roles: ['EMPLOYEE'], departmentId: departments[0].id, enabled: true, password: 'Device@2026Initial' } });
  expect(created.ok()).toBeTruthy();
  const first = await (await request.post('/api/auth/login', { data: { login: employeeNo, password: 'Device@2026Initial' } })).json();
  await request.post('/api/auth/password', { headers: { Authorization: 'Bearer ' + first.token }, data: { oldPassword: 'Device@2026Initial', newPassword: 'Device@2026Changed' } });
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page).toHaveTitle(/OA/);
  await page.getByLabel('工号 / 手机号').fill('admin');
  await page.getByLabel('密码', { exact: true }).fill(process.env.OA_ADMIN_PASSWORD || 'Admin@2026Verified');
  await page.getByRole('button', { name: '登录管理后台' }).click();
  await page.locator('nav').getByRole('button', { name: '账号与角色' }).click();
  const row = page.getByRole('row').filter({ hasText: employeeNo });
  await row.getByRole('button', { name: '编辑', exact: true }).click();
  let dialog = page.getByRole('dialog');
  await dialog.getByLabel('职务', { exact: true }).fill('项目主管');
  await dialog.getByLabel('工作电话', { exact: true }).fill('021-12345678');
  await dialog.getByRole('button', { name: '保存', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(row).toContainText('项目主管');
  await expect(row).toContainText('021-12345678');
  const employeeLogin = await (await request.post('/api/auth/login', { data: { login: employeeNo, password: 'Device@2026Changed', deviceName: '浏览器验收安卓', platform: 'Android' } })).json();
  await row.getByRole('button', { name: '登录设备' }).click();
  dialog = page.getByRole('dialog');
  await expect(dialog).toContainText('浏览器验收安卓');
  await expect(dialog.getByRole('heading', { name: '登录设备', exact: true })).toBeVisible();
  await dialog.screenshot({ path: '../.runtime/flutter-admin-devices.png' });
  expect(errors).toEqual([]);
  await dialog.getByRole('button', { name: '退出此设备' }).click();
  await expect(dialog).toContainText('暂无有效设备');
  const me = await request.get('/api/auth/me', { headers: { Authorization: 'Bearer ' + employeeLogin.token } });
  expect(me.status()).toBe(401);
});

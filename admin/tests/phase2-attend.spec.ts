import { test, expect } from '@playwright/test';

let restore: { headers: Record<string, string>, data: Record<string, any> } | undefined;
test.afterEach(async ({ request }) => {
  if (restore) expect((await request.put('/api/admin/workflow', restore)).ok()).toBeTruthy();
  restore = undefined;
});

test('中文后台配置、代提加班和补卡、审批、余额及来源标记', async ({ page, request }) => {
  page.setDefaultTimeout(10000);
  const password = process.env.OA_ADMIN_PASSWORD || 'Admin@2026Verified';
  const login = await (await request.post('/api/auth/login', { data: { login: 'admin', password } })).json();
  const headers = { Authorization: 'Bearer ' + login.token };
  const config = await (await request.get('/api/admin/workflow', { headers })).json();
  const settings = { leaveThreshold: config.leave_threshold, travelThreshold: config.travel_threshold, expenseThreshold: config.expense_threshold, financeId: config.finance_id, correctionDays: config.correction_days, overtimeRatio: config.overtime_ratio };
  restore = { headers, data: settings };
  const stamp = Date.now();
  const users = await (await request.get('/api/admin/users', { headers })).json();
  const manager = users.find((u: any) => u.enabled && u.roles.includes('SUPERVISOR'));
  const department = await (await request.post('/api/admin/departments', { headers, data: { name: '二期浏览器' + stamp } })).json();
  const name = '加班补卡验收' + stamp;
  const created = await request.post('/api/admin/users', { headers, data: { employeeNo: 'attend' + stamp, name, roles: ['EMPLOYEE'], departmentId: department.id, managerId: manager.id, enabled: true, password: 'Attend@2026Initial' } });
  expect(created.ok()).toBeTruthy();
  const uid = (await created.json()).id;
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  page.on('dialog', d => d.accept());
  const nav = (label: string) => page.locator('nav').getByRole('button', { name: label }).click();
  const dialog = page.getByRole('dialog');
  {
    await page.goto('/');
    await expect(page).toHaveTitle(/OA/);
    expect(page.url()).toContain('127.0.0.1:5173');
    await page.getByLabel('工号 / 手机号').fill('admin');
    await page.getByLabel('密码', { exact: true }).fill(password);
    await page.getByRole('button', { name: '登录管理后台' }).click();
    await nav('审批分流');
    await page.getByLabel('补卡期限（补卡日期结束后自然日数）').fill('5');
    await page.getByLabel('加班兑换调休比例').fill('1.25');
    await page.getByRole('button', { name: '保存分流配置' }).click();
    await expect.poll(async () => (await (await request.get('/api/attendance-policy', { headers })).json()).overtime_ratio).toBe(1.25);
    await nav('审批单据');
    await page.getByRole('button', { name: '提交申请', exact: true }).click();
    await dialog.getByLabel('代提交员工').selectOption(String(uid));
    await dialog.getByLabel('申请类型', { exact: true }).selectOption('OVERTIME');
    await dialog.getByLabel('抄送同事（可多选）').selectOption(String(manager.id));
    const day = new Date(Date.now() + 86400000 * 15).toISOString().slice(0, 10);
    await dialog.getByLabel('开始日期').fill(day);
    await dialog.getByLabel('结束日期').fill(day);
    await dialog.getByLabel('结束时间').selectOption('13:00');
    await dialog.getByLabel('申请理由').fill('浏览器加班' + stamp);
    await dialog.getByRole('button', { name: '保存', exact: true }).click();
    await expect(dialog).not.toBeVisible();
    await page.getByLabel('员工').selectOption(String(uid));
    await page.getByLabel('类型').selectOption('OVERTIME');
    await page.getByRole('button', { name: '查询', exact: true }).click();
    await page.getByRole('row').filter({ hasText: name }).getByRole('button', { name: '查看 / 审批' }).click();
    await expect(dialog).toContainText('0.625 天调休');
    await expect(dialog).toContainText(manager.name);
    await dialog.getByRole('button', { name: '提交审批' }).click();
    await expect(dialog).toContainText('加班 / 已批准');
    await page.screenshot({ path: '/tmp/oa-phase2-overtime.png', fullPage: true });
    await dialog.getByRole('button', { name: '关闭弹窗', exact: true }).click();
    await nav('假期余额');
    await expect(page.getByRole('row').filter({ hasText: name })).toContainText('0.625');
    await nav('余额流水');
    await expect(page.getByRole('row').filter({ hasText: name })).toContainText('加班批准计入');
    await nav('审批单据');
    await page.getByRole('row').filter({ hasText: name }).getByRole('button', { name: '查看 / 审批' }).click();
    await expect(dialog.getByRole('button', { name: '撤销申请', exact: true })).toBeVisible();
    await dialog.getByRole('button', { name: '撤销申请', exact: true }).click();
    await expect(dialog).toContainText('加班 / 已撤销');
    await dialog.getByRole('button', { name: '关闭弹窗', exact: true }).click();
    await expect(dialog).not.toBeVisible();
    await expect(page.getByRole('row').filter({ hasText: name })).toContainText('已撤销');
    await page.getByRole('button', { name: '提交申请', exact: true }).click();
    await dialog.getByLabel('代提交员工').selectOption(String(uid));
    await dialog.getByLabel('申请类型', { exact: true }).selectOption('CORRECTION');
    const yesterday = new Date(Date.now() - 86400000).toISOString().slice(0, 10);
    await dialog.getByLabel('补卡时间（北京时间）').fill(yesterday + 'T10:21');
    await dialog.getByLabel('申请理由').fill('浏览器补卡' + stamp);
    await dialog.getByRole('button', { name: '保存', exact: true }).click();
    await expect(dialog).not.toBeVisible();
    await page.getByLabel('类型').selectOption('CORRECTION');
    await page.getByRole('button', { name: '查询', exact: true }).click();
    await page.getByRole('row').filter({ hasText: name }).getByRole('button', { name: '查看 / 审批' }).click();
    await expect(dialog).toContainText('补卡类型：正常打卡');
    await dialog.getByRole('button', { name: '提交审批' }).click();
    await expect(dialog).toContainText('补卡 / 已批准');
    await expect(dialog.getByRole('button', { name: '撤销申请', exact: true })).toHaveCount(0);
    await dialog.getByRole('button', { name: '关闭弹窗', exact: true }).click();
    await nav('打卡记录');
    await page.getByLabel('员工').selectOption(String(uid));
    await page.getByLabel('类型').selectOption('');
    await page.getByRole('button', { name: '查询', exact: true }).click();
    await expect(page.getByRole('row').filter({ hasText: name })).toContainText('补卡');
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: '导出 CSV' }).click();
    expect((await download).suggestedFilename()).toMatch(/csv$/);
    await expect(page.locator('vite-error-overlay')).toHaveCount(0);
    await page.screenshot({ path: '/tmp/oa-phase2-punches.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(page.getByRole('heading', { name: '打卡记录', exact: true, level: 1 })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
    await page.screenshot({ path: '/tmp/oa-phase2-mobile.png', fullPage: true });
    expect(errors).toEqual([]);
  }
});
